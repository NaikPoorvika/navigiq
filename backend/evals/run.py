"""Run the evaluation suites and write reports.

    python -m evals.run                         # every suite, test split, rules only
    python -m evals.run --suite intent,tripspec --split dev
    python -m evals.run --llm both --write-docs # rules-only AND rules+LLM, update docs

`--llm on` uses the configured Ollama model (ADR-012); the run fails fast if
it is unreachable rather than silently reporting rules-only numbers.
Results: data/artifacts/reports/eval_<suite>_<config>_<split>.json, and with
--write-docs a summary at docs/reports/evaluation.md.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

from .common import SuiteResult, reports_dir

SUITES = ["intent", "tripspec", "modification", "references", "rag", "answers"]
LLM_SUITES = {"intent", "tripspec", "modification", "answers"}


async def _llm_service():
    from app.config import settings
    from app.llm.factory import build_llm_gateway
    from app.llm.service import LLMService
    gateway = build_llm_gateway(settings)
    svc = LLMService(gateway, enabled=True, max_concurrency=1, queue_timeout_s=300,
                     breaker_threshold=50, cache_ttl_s=0)
    return svc


async def run_suite(name: str, db, llm, split: str, config: str) -> SuiteResult:
    from importlib import import_module
    mod = import_module(f"evals.{name}")
    return await mod.run(db, llm=llm, split=split, config=config)


async def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", default="all")
    ap.add_argument("--split", default="test", choices=["dev", "test", "all"])
    ap.add_argument("--llm", default="off", choices=["off", "on", "both"])
    ap.add_argument("--write-docs", action="store_true")
    ap.add_argument("--show-failures", type=int, default=15)
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    suites = SUITES if args.suite == "all" else args.suite.split(",")

    from app.db.session import AsyncSessionLocal
    configs: list[tuple[str, object]] = []
    if args.llm in ("off", "both"):
        configs.append(("rules", None))
    if args.llm in ("on", "both"):
        svc = await _llm_service()
        from app.llm.prompts import INTENT
        try:
            await svc.run(INTENT, message="hello", pending_question="none", has_plan="no")
        except Exception as exc:  # noqa: BLE001
            print(f"LLM unavailable ({type(exc).__name__}: {exc}); refusing to report "
                  "rules-only numbers as LLM numbers", file=sys.stderr)
            return 2
        configs.append((f"rules+llm({svc.model_for('intent_classify')})", svc))

    results: list[SuiteResult] = []
    for name in suites:
        for config, llm in configs:
            if llm is not None and name not in LLM_SUITES:
                continue
            t0 = time.perf_counter()
            async with AsyncSessionLocal() as db:
                res = await run_suite(name, db, llm, args.split, config)
            res.breakdown["seconds"] = round(time.perf_counter() - t0, 1)
            results.append(res)
            out = reports_dir() / f"eval_{name}_{'llm' if llm else 'rules'}_{args.split}.json"
            out.write_text(json.dumps(res.to_dict(), indent=2, ensure_ascii=False),
                           encoding="utf-8")
            _print(res, args.show_failures)
    if args.write_docs:
        write_docs(results, args.split)
    return 0 if all(r.passed for r in results) else 1


def _print(res: SuiteResult, show: int) -> None:
    status = "PASS" if res.passed else "FAIL"
    print(f"\n== {res.suite} [{res.config}] split={res.split} n={res.n}  {status}")
    for k, v in res.metrics.items():
        print(f"   {k:32s} {v}")
    for k, (v, t, ok) in res.gates.items():
        print(f"   gate {k:27s} {v} {t} {'ok' if ok else 'MISSED'}")
    for f in res.failures[:show]:
        print("   x", json.dumps(f, ensure_ascii=False)[:220])


def write_docs(results: list[SuiteResult], split: str) -> None:
    from app.core.paths import REPO_ROOT
    path = Path(REPO_ROOT) / "docs" / "reports" / "evaluation.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# NavigIQ evaluation report", "",
             f"Split: **{split}** (test examples are never used to tune the system). "
             "Generated by `python -m evals.run --llm both --write-docs` from "
             "`data/evals/*.jsonl`. Fixed evaluation clock: Monday 2026-09-21 10:00 IST.", "",
             "| Suite | Configuration | n | Key metrics | Gates |", "|---|---|---|---|---|"]
    for r in results:
        metrics = "; ".join(f"{k} {v}" for k, v in list(r.metrics.items())[:6])
        gates = "; ".join(f"{k} {v} ({t}) {'✓' if ok else '✗'}"
                          for k, (v, t, ok) in r.gates.items()) or "—"
        lines.append(f"| {r.suite} | {r.config} | {r.n} | {metrics} | {gates} |")
    lines += ["", "## Details", ""]
    for r in results:
        lines += [f"### {r.suite} — {r.config}", ""]
        for k, v in r.breakdown.items():
            if k in ("per_intent",):
                continue
            lines.append(f"- **{k}**: `{json.dumps(v, ensure_ascii=False)[:600]}`")
        if r.failures:
            lines.append(f"- **failures ({len(r.failures)})**, first few:")
            for f in r.failures[:8]:
                lines.append(f"  - `{json.dumps(f, ensure_ascii=False)[:240]}`")
        lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {path}")


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
